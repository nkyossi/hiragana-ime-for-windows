# Generates src/core/NumericTable.inc: the code point ranges for which
# Python's str.isnumeric() is true. Dictionary::lookup() uses it the same way
# engine/dictionary.py does.
import os
import sys

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'core', 'NumericTable.inc')
ranges = []
start = None
for cp in range(0x110000):
    ok = chr(cp).isnumeric()
    if ok and start is None:
        start = cp
    if not ok and start is not None:
        ranges.append((start, cp - 1))
        start = None
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'// Generated by tools/gen_numeric.py from Python {sys.version.split()[0]} str.isnumeric(); do not edit.\n')
    for a, b in ranges:
        f.write(f'{{0x{a:X}, 0x{b:X}}},\n')
